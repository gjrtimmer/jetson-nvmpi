#!/usr/bin/env bash
# Regenerate test/api/dec_color_fixture.h (decoder colour cases, #163).
# Needs ffmpeg with libx264, ffprobe, xxd and python3 on the host. Safe to
# re-run: the header is rewritten from scratch.
# usage: test/api/gen_dec_color_fixture.sh [output.h]
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
out=${1:-$here/dec_color_fixture.h}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# name matrix(ffmpeg scale) colorspace-tag primaries-tag trc-tag range(scale) range(tag)
clips=(
  "bt601_limited bt601 smpte170m smpte170m smpte170m tv tv"
  "bt709_limited bt709 bt709 bt709 bt709 tv tv"
  "bt601_full bt601 smpte170m smpte170m smpte170m full pc"
  "bt709_full bt709 bt709 bt709 bt709 full pc"
)

{
  cat <<'H'
/*
 * dec_color_fixture.h - GENERATED by gen_dec_color_fixture.sh, do not edit.
 * Four H.264 clips (320x240, 2 frames: IDR + P, no B-frames, repeat-headers,
 * x264 crf 10) with the colorimetry and range signalled in the VUI, plus a
 * reference taken from a software decode of the same stream (ffmpeg, native
 * pixel format, no conversion):
 *   *_ymean/_umean/_vmean  mean of each 16x16 luma / 8x8 chroma block
 *                          (20x15 blocks), per frame
 *   *_yrow/_urow/_vrow     luma rows DECCOL_YROWS and chroma row DECCOL_CROW
 *                          in full, per frame
 * Regenerate: test/api/gen_dec_color_fixture.sh
 */
#ifndef NVMPI_TEST_DEC_COLOR_FIXTURE_H
#define NVMPI_TEST_DEC_COLOR_FIXTURE_H

#define DECCOL_W 320
#define DECCOL_H 240
#define DECCOL_FRAMES 2
#define DECCOL_BLOCKS 300                /* 20 x 15 per plane and frame */
#define DECCOL_YROWS { 8, 120, 232 }
#define DECCOL_CROW 60

H
  for c in "${clips[@]}"; do
    read -r name mx cs cp ct rs rt <<<"$c"
    ffmpeg -v error -y -f lavfi -i testsrc2=s=320x240:r=24 -frames:v 2 \
      -vf "scale=out_color_matrix=$mx:out_range=$rs,format=yuv420p" \
      -c:v libx264 -preset veryslow -crf 10 \
      -colorspace "$cs" -color_primaries "$cp" -color_trc "$ct" -color_range "$rt" \
      -x264-params "keyint=2:bframes=0:repeat-headers=1:aud=0:sei=0:scenecut=0" \
      -f h264 "$tmp/$name.h264"
    # Native software decode, bytes untouched (no -pix_fmt: no range conversion).
    ffmpeg -v error -y -i "$tmp/$name.h264" -frames:v 2 -f rawvideo "$tmp/$name.yuv"
    ffprobe -v error -select_streams v:0 -show_entries stream=pix_fmt,color_range \
      -of csv=p=0 "$tmp/$name.h264" >&2
    (cd "$tmp" && xxd -i -n "deccol_${name}_es" "$name.h264" | sed 's/^unsigned char/static const unsigned char/; s/^unsigned int/static const unsigned int/')
    python3 -I - "$tmp/$name.yuv" "$name" <<'P'
import sys
W, H, N = 320, 240, 2
path, name = sys.argv[1], sys.argv[2]
raw = open(path, "rb").read()
fs = W * H * 3 // 2
assert len(raw) == fs * N, len(raw)

def emit(label, vals):
    print("static const unsigned char deccol_%s_%s[] = {" % (name, label))
    for i in range(0, len(vals), 16):
        print("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    print("};")

def means(plane, w, h, b):
    out = []
    for by in range(h // b):
        for bx in range(w // b):
            s = sum(plane[(by * b + y) * w + bx * b + x] for y in range(b) for x in range(b))
            out.append((s + b * b // 2) // (b * b))
    return out

ym, um, vm, yr, ur, vr = [], [], [], [], [], []
for f in range(N):
    fr = raw[f * fs:(f + 1) * fs]
    y, u, v = fr[:W * H], fr[W * H:W * H * 5 // 4], fr[W * H * 5 // 4:]
    ym += means(y, W, H, 16)
    um += means(u, W // 2, H // 2, 8)
    vm += means(v, W // 2, H // 2, 8)
    for r in (8, 120, 232):
        yr += list(y[r * W:(r + 1) * W])
    ur += list(u[60 * (W // 2):61 * (W // 2)])
    vr += list(v[60 * (W // 2):61 * (W // 2)])
for lab, vals in (("ymean", ym), ("umean", um), ("vmean", vm), ("yrow", yr), ("urow", ur), ("vrow", vr)):
    emit(lab, vals)
P
  done
  echo
  echo "#endif /* NVMPI_TEST_DEC_COLOR_FIXTURE_H */"
} >"$tmp/out.h"
mv "$tmp/out.h" "$out"
